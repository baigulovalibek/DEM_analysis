"""
Regression tests that lock the analysis pipeline against fixed reference
outputs stored under :mod:`tests/fixtures/`.

The fixtures are generated by :mod:`tests.build_fixtures` immediately after
Phase A; every subsequent change (Phase B JIT kernels, Phase C algorithmic
swaps) must reproduce these arrays within the documented tolerance.

Tolerance policy follows OPTIMIZATION.md §7:

* **Integer / categorical** outputs (flow direction, stream mask, viewshed,
  Strahler order): ``np.array_equal`` exact match.
* **Priority-flood filled DEM**: bit-identical — algorithm is deterministic.
* **Other float outputs**: max-RMS = 1e-5 (covers the float32 horizon
  dtype change in A.6 with room to spare for IEEE-754 reorderings).

Run with ``pytest tests/test_regression.py``.
"""
from __future__ import annotations
from pathlib import Path

import numpy as np
import pytest

from tests.synth_dem import NODATA, make_dem, make_dem_with_void


SIZE = 512
CELL_SIZE = 30.0
FIXTURE_DIR = Path(__file__).resolve().parent / "fixtures"
FIXTURES_PRESENT = (FIXTURE_DIR / f"dem_{SIZE}.npy").exists()


pytestmark = pytest.mark.skipif(
    not FIXTURES_PRESENT,
    reason=f"fixtures missing — run `python -m tests.build_fixtures --size {SIZE}` first",
)


def _load(name: str) -> np.ndarray:
    return np.load(FIXTURE_DIR / f"{name}.npy")


def _assert_close(actual: np.ndarray, expected: np.ndarray, rms_tol: float = 1e-5) -> None:
    assert actual.shape == expected.shape
    assert actual.dtype == expected.dtype
    diff = actual.astype(np.float64) - expected.astype(np.float64)
    # NaN positions must match; everywhere else the RMS must be tiny.
    a_nan = ~np.isfinite(actual)
    e_nan = ~np.isfinite(expected)
    assert np.array_equal(a_nan, e_nan), (
        f"NaN mask differs: {int(np.sum(a_nan ^ e_nan))} mismatched cells"
    )
    finite = ~a_nan
    if finite.any():
        rms = float(np.sqrt(np.mean(diff[finite] ** 2)))
        assert rms <= rms_tol, f"RMS {rms:.3e} exceeds tolerance {rms_tol:.0e}"


def _assert_exact(actual: np.ndarray, expected: np.ndarray) -> None:
    assert actual.shape == expected.shape
    assert actual.dtype == expected.dtype
    assert np.array_equal(actual, expected), "outputs differ from locked fixture"


# ── inputs are themselves locked, so regenerating them must be deterministic ──

def test_synth_dem_is_deterministic() -> None:
    _assert_exact(make_dem(SIZE), _load(f"dem_{SIZE}"))
    _assert_exact(make_dem_with_void(SIZE), _load(f"dem_void_{SIZE}"))


