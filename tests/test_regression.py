def test_streams_and_strahler(filled: np.ndarray) -> None:
    from app.core.hydrology.flow_direction import d8_flow_direction
    from app.core.hydrology.flow_accumulation import d8_flow_accumulation
    from app.core.hydrology.streams import extract_streams, strahler_order
    fd = d8_flow_direction(filled, CELL_SIZE)
    fa = d8_flow_accumulation(filled, fd)
    streams = extract_streams(fa, threshold=float(np.nanpercentile(fa, 99)))
    _assert_exact(streams, _load(f"streams_{SIZE}"))
    _assert_exact(strahler_order(streams, fd), _load(f"strahler_{SIZE}"))


